@ Palette dithering via a lookup table. Per 2x2 block (one chroma pair in
@ 4:2:0; or 4x4 with FX_PIX4, video_cave.s fx4) fx_strip averages the luma,
@ takes it through the preset's luma map (its contrast and brightness, and
@ the Game Boy tone), sharpens it against its row neighbours, adds the
@ look's dither offset, then looks the block's (Y, U, V) up in a table that
@ holds the nearest palette colour (or for a ramp, FX_RAMP, the even shade of
@ its luma). tools/sim_look.py is the exact reference. The table (33x33x33: Y, U, V in steps of 8, bins
@ centred on multiples of 8) is filled once per photo by lut_build, entered
@ from idx_stub (hooks FUN_000187c4, the capture handler, task context), which
@ also sets the photo's preset: the one chosen with the center button (the
@ mode, kept in the camera's saved settings, see lcd_cave.s), or a random one
@ per photo in the rnd mode. A preset is
@ a match palette (the table holds the nearest of its colours) and a film
@ simulation (the hook paints that colour as the film renders it: CUR_PAL
@ points at the preset's film colours). On the first strip of each photo
@ the hook also draws the preset's tag in the top right corner. The normal
@ mode (NPAL + 1, after rnd) has no effect: lut_fill leaves CUR_PAL at 0, so
@ both hooks leave the photo or video alone (and its size is the factory's,
@ see lcd_cave.s).
@ Presets and tags come from tools/palettes.py (palettes.inc, generated by
@ build.sh) and live in preset_data.s, whose addresses build.sh passes in.
@ Only `hook` has a fixed address; build.sh reads the others
@ (idx_stub, the aspect-ratio stubs, and lut_fill / VARS for the video
@ hook) from the object file.
    .syntax unified
    .arm
    .include "palettes.inc"               @ NPAL, TAG_*, FX_*, MAX_BLOCKS
    .include "look.inc"                   @ VARS offsets, CLAMP, SHARPEN, LOOKUP
base:
    .set    MATCH_PALETTES, base + MATCH_ADDR    @ preset_data.s (from build.sh)
    .set    PRESET_MATCH,   base + PMATCH_ADDR
    .set    DISPLAY_PTRS,   base + DPTRS_ADDR
    .set    TAGS,           base + TAGS_ADDR
    .set    PRESET_FX,      base + FX_ADDR    @ per preset: flags, contrast, brightness, sharpening
    .set    GB_TONE_FILL,   base + GBTONE_ADDR @ preset_data.s: the Game Boy tone, over a luma map
    .set    UDIV,           base + UDIV_ADDR  @ preset_data.s: r0 / r1
    .set    FX4,            base + 0xbb774    @ video_cave.s: fx_strip for 4x4 blocks (fixed)
    .set    RESUME,      base + 0x1544c
    .set    PHOTO_PATH,  base + 0xf188
    .set    VIDEO_PATH,  base + 0xf410
    .set    RESUME187,   base + 0x187c8
    .set    CACHE_INV,   base + 0x401ac
    .set    CACHE_CLEAN, base + 0x401b8
    .set    MALLOC,      base + 0x5374c   @ pvPortMalloc(size, align)
    .equ    PHOTO,       0x1317ac
    .equ    STRIP_BYTES, 0x13155c
    .equ    TICK,        0x126b80         @ FreeRTOS xTickCount
    .equ    LUT_N,       33               @ entries per axis: (x + 4) >> 3
    .equ    LUT_SIZE,    LUT_N * LUT_N * LUT_N
    .equ    FX_CONTRAST, 1                @ offsets into a PRESET_FX record (byte 0: the flags)
    .equ    FX_BRIGHT,   2
    .equ    FX_SHARP,    3
    .equ    CFG,         0x132160         @ the camera's settings, saved to NVRAM at power-off
    .equ    CFG_MODE,    0xf1             @ our byte in it: chosen preset, or NPAL = random (lcd_cave.s)
    .if     TAG_SCALE != 2
    .error  "the tag drawing below writes 2x2 blocks per font pixel"
    .endif

    .org    0xbab6c
hook:
    push    {r0-r11, lr}                  @ r0-r3 are the callback's live args
    sub     r3, r0, #0x200000
    cmp     r3, #0xe00000
    bhs     done
    ldr     r4, =PHOTO
    ldr     r6, =STRIP_BYTES
    ldr     r6, [r6]
    cmp     r6, #96
    bls     done
    ldr     r5, [r4, #0x18]
    cmp     r1, r5
    beq     1f
    add     r5, r5, r6
    cmp     r1, r5
    bne     done
1:  ldr     r0, =VARS - base                     @ table ready? (0 while building or
    ldr     r12, [r0, #LUT_PTR]           @  if the allocation failed)
    ldr     r5, [r0, #CUR_PAL]
    cmp     r12, #0
    cmpne   r5, #0
    beq     done
    ldr     r11, [r4, #0x18]              @ r11 = buffer A (base) = even_base
    mov     r7, r6, lsr #5                @ r7 = stride = width * 3/2
    ldr     r2, =0xAAAAAAAB
    umull   r0, r3, r7, r2
    mov     r8, r3, lsr #1                @ r8 = third = width/2
    mov     r0, r11                       @ invalidate the 64-row span
    mov     r1, r7, lsl #6
    mov     lr, pc
    b       CACHE_INV
    mov     lr, pc                        @ the look (r5 = paint colours, kept)
    b       fx_strip
    @ ---- first strip of the photo: draw the palette tag, top right ----
    ldr     r0, =VARS - base
    ldr     r1, [r0, #STRIP_N]
    add     r2, r1, #1
    str     r2, [r0, #STRIP_N]
    cmp     r1, #0
    bne     clean
    mov     lr, pc
    b       draw_tag
clean:
    mov     r0, r11
    mov     r1, r7, lsl #6
    mov     lr, pc
    b       CACHE_CLEAN
done:
    pop     {r0-r11, lr}
    str     lr, [sp, #-4]!
    b       RESUME
    .ltorg

@ The look, on one 64-row strip; both hooks call this. r11 = strip, r7 =
@ stride (1.5 W), r8 = third (W / 2). All registers preserved. Per row of
@ blocks: first every block's mapped luma into the row buffer (so sharpening
@ sees its neighbours as they were), then each block: sharpening, the dither
@ offset of its position, its U, V, the table, painted. 4x4 blocks: fx4 in
@ the video cave, which ends as fxdone does.
fx_strip:
    push    {r0-r12, lr}
    sub     sp, sp, #4                    @ [sp] = the sharpening weight
    cmp     r8, #MAX_BLOCKS               @ wider than any of ours (the row buffer): leave it
    bhi     fxdone
    ldr     r0, =VARS - base
    ldr     r12, [r0, #LUT_PTR]           @ r12 = table
    ldr     r5, [r0, #CUR_PAL]            @ r5 = paint colours
    ldrb    r1, [r0, #SHARP_W]
    str     r1, [sp]
    ldrb    r1, [r0, #FLAGS]
    sub     r4, r12, #ROWBUF_BYTES + YMAP_BYTES
    add     r4, r4, #1                    @ r4 = the row buffer (padded: -1 is free)
    tst     r1, #FX_PIX4
    bne     FX4
    mov     r10, #0                       @ r10 = band (a row of 2x2 blocks), 0..31
fx2:
    sub     lr, r12, #YMAP_BYTES          @ lr = the luma map
    add     r6, r11, r7
    add     r6, r6, r8                    @ r6 = the odd row's luma
    mov     r9, #0                        @ r9 = block c, x = 2c
1:  add     r2, r11, r9, lsl #1
    ldrb    r0, [r2]
    ldrb    r1, [r2, #1]
    add     r0, r0, r1
    add     r2, r6, r9, lsl #1
    ldrb    r1, [r2]
    add     r0, r0, r1
    ldrb    r1, [r2, #1]
    add     r0, r0, r1
    ldrb    r0, [lr, r0, lsr #2]          @ the 4 luma's mean, mapped
    strb    r0, [r4, r9]
    add     r9, r9, #1
    cmp     r9, r8
    blo     1b
    PAD     r8
    ldr     lr, =VARS - base + DITHER
    and     r0, r10, #3
    add     lr, lr, r0, lsl #2            @ lr = this band's 4 dither offsets
    mov     r9, #0
2:  ldrb    r0, [r4, r9]
    SHARPEN
    and     r1, r9, #3
    ldrsb   r1, [lr, r1]
    add     r0, r0, r1
    CLAMP
    cmp     r9, r8, lsr #1                @ the chroma pair: in the even row's chroma,
    addlo   r6, r11, r8, lsl #1           @  or the odd row's
    addlo   r6, r6, r9, lsl #1
    subhs   r1, r9, r8, lsr #1
    addhs   r6, r11, r7
    addhs   r6, r6, r1, lsl #1            @ r6 = the pair
    ldrb    r1, [r6]
    ldrb    r2, [r6, #1]
    LOOKUP
    strb    r1, [r6]                      @ paint the block
    strb    r2, [r6, #1]
    add     r6, r11, r9, lsl #1
    strb    r0, [r6]
    strb    r0, [r6, #1]
    add     r6, r6, r7
    add     r6, r6, r8
    strb    r0, [r6]
    strb    r0, [r6, #1]
    add     r9, r9, #1
    cmp     r9, r8
    blo     2b
    add     r11, r11, r7, lsl #1          @ next band
    add     r10, r10, #1
    cmp     r10, #32
    blo     fx2
fxdone:
    add     sp, sp, #4
    pop     {r0-r12, pc}
    .ltorg

@ Draw the current preset's tag in the top right corner of a strip:
@ r11 = strip base, r7 = stride, r8 = third, r5 = the preset's film colours.
@ All registers preserved. Called by the photo hook on a photo's first strip
@ and by the video hook (video_cave.s) on every frame's first strip.
draw_tag:
    push    {r0-r12, lr}
    ldr     r0, =VARS - base
    ldr     r1, [r0, #PAL_IDX]
    ldr     r3, =TAGS - base
    mov     r2, #TAG_BYTES
    mla     r3, r1, r2, r3                @ r3 = this palette's tag record
    mov     lr, #0                        @ lr = cell index (row-major)
    mov     r10, #0                       @ r10 = cell row
tagrow:
    mov     r9, #0                        @ r9 = cell column
tagcell:
    ldrb    r4, [r3, lr, lsr #2]          @ 2 bits per cell, LSB first
    and     r6, lr, #3
    mov     r6, r6, lsl #1
    mov     r4, r4, lsr r6
    ands    r4, r4, #3                    @ 0 = leave, 1 = dark, 2 = light
    beq     tagnext
    add     r4, r3, r4
    ldrb    r4, [r4, #TAG_BYTES - 3]      @ dark / light colour offset
    add     r4, r5, r4
    ldrb    r0, [r4]                      @ Y
    ldrb    r1, [r4, #1]                  @ U
    ldrb    r2, [r4, #2]                  @ V
    mov     r6, #TAG_TOP
    add     r6, r6, r10, lsl #1           @ first band of the cell
    mul     r12, r6, r7
    add     r6, r11, r12, lsl #1          @ r6 = its even_base
    sub     r12, r8, #TAG_RIGHT + TAG_COLS * TAG_SCALE
    add     r12, r12, r9, lsl #1          @ r12 = first block column (right half)
    .rept   2                             @ 2 bands x 2 blocks
    add     r4, r6, r12, lsl #1           @ even luma, 4 pixels
    strb    r0, [r4]
    strb    r0, [r4, #1]
    strb    r0, [r4, #2]
    strb    r0, [r4, #3]
    add     r4, r4, r7
    add     r4, r4, r8                    @ odd luma, 4 pixels
    strb    r0, [r4]
    strb    r0, [r4, #1]
    strb    r0, [r4, #2]
    strb    r0, [r4, #3]
    add     r4, r6, r7                    @ chroma pairs: odd row, at 2c - third
    add     r4, r4, r12, lsl #1
    sub     r4, r4, r8
    strb    r1, [r4]
    strb    r2, [r4, #1]
    strb    r1, [r4, #2]
    strb    r2, [r4, #3]
    add     r6, r6, r7, lsl #1            @ next band
    .endr
tagnext:
    add     lr, lr, #1
    add     r9, r9, #1
    cmp     r9, #TAG_COLS
    blo     tagcell
    add     r10, r10, #1
    cmp     r10, #TAG_ROWS
    blo     tagrow
    pop     {r0-r12, pc}
    .ltorg

@ Once per photo, before the capture starts (idx_stub, FUN_000187c4).
lut_build:
    push    {r0-r12, lr}
    mov     lr, pc
    b       lut_fill
    pop     {r0-r12, lr}
    push    {r3, r4, r5, r6, r7, lr}      @ replaced instruction from 0x187c4
    b       RESUME187

@ Use the chosen preset (the mode byte; out of range = the first), or in the
@ rnd mode a random one (never the last one). The normal mode turns the
@ hooks off (CUR_PAL = 0) and that's all. If the table already holds
@ the preset, keep it (saves the ~50-70 ms
@ fill before the capture). Otherwise allocate the table on first use (with
@ the luma map in the YMAP_BYTES before it), and fill
@ it with the nearest colour of the preset's match palette (2*|dY| + |dU| + |dV|,
@ first wins on a tie) at each bin centre; then the luma map, from the preset's
@ contrast and brightness: Y' = (Y - 128) * contrast / 128 + 128 + brightness
@ (the shift rounds down), clamped to 0..255; then point CUR_PAL at the preset's
@ film colours. The last bin's centre is 256, not 255: that adds the same amount
@ to every distance, so the winner is unchanged. A plain subroutine (all
@ registers preserved), also called by the video hook (video_cave.s) at the
@ start of each recording.
lut_fill:
    push    {r0-r12, lr}
    ldr     r4, =VARS - base
    mov     r0, #0
    str     r0, [r4, #STRIP_N]            @ next strip is this photo's first
    ldr     r0, =CFG
    ldrb    r0, [r0, #CFG_MODE]
max_fill:
    cmp     r0, #NPAL + NORMAL_MODE
    movhi   r0, #0                        @ not a mode (e.g. never set): the first
npal1_fill:
    cmp     r0, #NPAL + 1                 @ the normal mode: no effect
    moveq   r1, #0
    streq   r1, [r4, #CUR_PAL]
    beq     9f
npal_fill:
    cmp     r0, #NPAL
    bne     1f                            @ a preset; == NPAL is rnd:
    mov     lr, pc                        @  a random preset
    b       pick
1:  ldr     r1, [r4, #PAL_IDX]
    cmp     r0, r1
    bne     4f
    ldr     r1, [r4, #CUR_PAL]
    cmp     r1, #0                        @ same preset, table complete: keep it
    bne     9f
4:  mov     r1, #0
    str     r1, [r4, #CUR_PAL]            @ hook off until the table is complete
    str     r0, [r4, #PAL_IDX]
    ldr     r6, [r4, #LUT_PTR]
    cmp     r6, #0
    bne     2f
    ldr     r0, =ROWBUF_BYTES + YMAP_BYTES + LUT_SIZE
    mov     r1, #0x40
    mov     lr, pc
    b       MALLOC
    ldr     r4, =VARS - base
    movs    r6, r0
    beq     9f                            @ no memory: photo stays unprocessed
    add     r6, r6, #ROWBUF_BYTES + YMAP_BYTES  @ r6 = table write pointer
    str     r6, [r4, #LUT_PTR]
2:  ldr     r0, [r4, #PAL_IDX]
    ldr     r5, =PRESET_MATCH - base
    ldrb    r0, [r5, r0]                  @ r0 = the preset's match palette
    ldr     r5, =MATCH_PALETTES - base    @ skip to it: each is a count byte
3:  subs    r0, r0, #1                    @  + count*3 bytes
    ldrbpl  r1, [r5]
    addpl   r5, r5, #1
    addpl   r5, r5, r1
    addpl   r5, r5, r1, lsl #1
    bpl     3b
    ldrb    r12, [r5], #1                 @ r5 = colours, r12 = count
    strb    r12, [r4, #NCOL]
    ldr     r0, [r4, #PAL_IDX]
    ldr     r1, =PRESET_FX - base
    ldrb    r1, [r1, r0, lsl #2]
    tst     r1, #FX_RAMP
    bne     ramp
    add     r12, r12, r12, lsl #1         @ r12 = 3 * count
    mov     r7, #0                        @ r7/r8/r9 = Y/U/V bin centre
yl: mov     r8, #0
ul: mov     r9, #0
vl: mov     r2, r5
    mov     r3, #0                        @ r3 = offset of this colour
    mvn     r10, #0                       @ r10 = best distance
sl: ldrb    r1, [r2], #1
    subs    r1, r7, r1
    rsbmi   r1, r1, #0
    mov     r0, r1, lsl #1                @ 2*|dY|
    ldrb    r1, [r2], #1
    subs    r1, r8, r1
    rsbmi   r1, r1, #0
    add     r0, r0, r1
    ldrb    r1, [r2], #1
    subs    r1, r9, r1
    rsbmi   r1, r1, #0
    add     r0, r0, r1
    cmp     r0, r10
    movlo   r10, r0
    movlo   r11, r3                       @ r11 = best offset
    add     r3, r3, #3
    cmp     r3, r12
    blo     sl
    strb    r11, [r6], #1
    add     r9, r9, #8
    cmp     r9, #LUT_N * 8
    blo     vl
    add     r8, r8, #8
    cmp     r8, #LUT_N * 8
    blo     ul
    add     r7, r7, #8
    cmp     r7, #LUT_N * 8
    blo     yl
    b       filled
ramp:                                   @ a ramp: luma bin q -> its even shade, min(n - 1, 8qn >> 8),
    mov     r7, #0                        @  whatever U, V (the colours are sorted dark to light)
1:  mul     r0, r7, r12
    mov     r0, r0, lsr #5
    cmp     r0, r12
    subhs   r0, r12, #1
    add     r0, r0, r0, lsl #1            @ its offset, 3 * shade
    ldr     r1, =LUT_N * LUT_N
2:  strb    r0, [r6], #1
    subs    r1, r1, #1
    bne     2b
    add     r7, r7, #1
    cmp     r7, #LUT_N
    blo     1b
filled:
    ldr     r4, =VARS - base
    ldr     r0, [r4, #PAL_IDX]
    ldr     r1, =PRESET_FX - base
    add     r1, r1, r0, lsl #2
    ldrb    r9, [r1]                      @ r9 = the look's flags
    strb    r9, [r4, #FLAGS]
    ldrb    r2, [r1, #FX_SHARP]
    strb    r2, [r4, #SHARP_W]
    ldrb    r2, [r1, #FX_CONTRAST]
    ldrsb   r3, [r1, #FX_BRIGHT]
    add     r3, r3, #128
    ldr     r6, [r4, #LUT_PTR]
    sub     r6, r6, #YMAP_BYTES           @ r6 = the luma map
    mov     r7, #0
ym: sub     r1, r7, #128
    mul     r1, r2, r1
    add     r1, r3, r1, asr #7
    cmp     r1, #0
    movlt   r1, #0
    cmp     r1, #255
    movgt   r1, #255
    strb    r1, [r6, r7]
    add     r7, r7, #1
    cmp     r7, #256
    blo     ym
    tst     r9, #FX_GBTONE                @ then the Game Boy tone over it
    movne   r0, r6
    ldrbne  r1, [r4, #NCOL]
    movne   lr, pc
    bne     GB_TONE_FILL
    ldrb    r10, [r4, #NCOL]              @ the dither offsets: (B - 8) * 4, or for a ramp
    mov     r7, #0                        @  of n one shade, (2B + 1) * 8 / n - 128 / n
dt: ldr     r0, =BAYER - base
    ldrb    r0, [r0, r7]
    tst     r9, #FX_RAMP
    subeq   r0, r0, #8
    moveq   r0, r0, lsl #2
    beq     5f
    mov     r0, r0, lsl #4
    add     r0, r0, #8
    mov     r1, r10
    mov     lr, pc
    b       UDIV
    mov     r11, r0
    mov     r0, #128
    mov     r1, r10
    mov     lr, pc
    b       UDIV
    sub     r0, r11, r0
5:  add     r1, r4, #DITHER
    strb    r0, [r1, r7]
    add     r7, r7, #1
    cmp     r7, #16
    blo     dt
    ldr     r0, [r4, #PAL_IDX]
    ldr     r1, =DISPLAY_PTRS - base
    ldr     r5, [r1, r0, lsl #2]          @ the preset's film colours
    str     r5, [r4, #CUR_PAL]            @ table complete: hook on
9:  pop     {r0-r12, pc}
    .ltorg

@ r0 = a random preset, never PAL_IDX (so never the same twice in a row):
@ (ms tick & 0xff) mod NPAL. Clobbers r1. (The npal_* labels mark the
@ instructions whose immediate is NPAL, npal1_* NPAL + 1 and max_* NPAL +
@ NORMAL_MODE, the last mode: the site's editor rewrites them.)
pick:
    ldr     r0, =TICK
    ldr     r0, [r0]
    and     r0, r0, #0xff
npal_pick1:
1:  cmp     r0, #NPAL
npal_pick2:
    subhs   r0, r0, #NPAL
    bhs     1b
    ldr     r1, =VARS - base
    ldr     r1, [r1, #PAL_IDX]
    cmp     r0, r1                        @ same as the current one: take the next
    addeq   r0, r0, #1
npal_pick3:
    cmp     r0, #NPAL
    movhs   r0, #0
    mov     pc, lr
    .ltorg

    .align  2
BAYER:
    .byte   0, 8, 2, 10
    .byte   12, 4, 14, 6
    .byte   3, 11, 1, 9
    .byte   15, 7, 13, 5
VARS:
    .word   0                             @ LUT_PTR: table, allocated on first photo
    .word   0                             @ CUR_PAL: film colours of the table's preset, 0 = off
    .word   0xff                          @ PAL_IDX: last photo's preset (0xff = none yet)
    .word   0                             @ STRIP_N
    .byte   0, 0, 0, 0                    @ FLAGS, SHARP_W, NCOL
    .space  16                            @ DITHER

@ Size stubs, reached directly from the photo resolution jump table
@ (ldrls pc,[pc,idx,lsl#2] @ 0xf3c8, table @ 0xf3d0) and the video one
@ (@ 0xf098, table @ 0xf0a0). Each sets a crop of the sensor (scaled, not
@ cropped) and a small final size: r6/r7 = target, r0/r1 = crop, from
@ tools/palettes.py SIZES (~274k pixels each, the crop at the output's
@ aspect so nothing is stretched); photo and video get the same size since
@ v020 (v018/v019: video 640 wide at every aspect, in separate stubs).
@ Photo: first scaler = crop, the final scaler shrinks. Video has no such
@ final stage (IMG_0294: garbage), so there the first scaler = target, as in
@ every stock video size (IMG_0295: works).
@ r4 = size struct, r5 = APMode (0x101 video, 0x102 photo).
photo43:                                @ 4:3
vid43:
    ldr     r6, SIZES + 32
    ldr     r7, SIZES + 36
    ldr     r0, SIZES + 40
    ldr     r1, SIZES + 44
    b       size_common
stub169:                                @ 16:9
vid169:
    ldr     r6, SIZES
    ldr     r7, SIZES + 4
